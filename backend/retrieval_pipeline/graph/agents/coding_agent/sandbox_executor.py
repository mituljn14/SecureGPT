"""
sandbox_executor.py

STEP 5: Docker Python Sandbox.

Takes the code generated by llm_agent.py (Step 4) plus an optional mapping of
"path the code refers to" -> "actual file on disk" (resolved by
document_registry.db + file_reader.py in Steps 2-3), and executes it
inside an isolated, throwaway Docker container.

Guarantees enforced here:
  - no internet access             (--network none)
  - limited CPU                    (--cpus)
  - limited memory                 (--memory)
  - execution timeout              (subprocess timeout + docker kill)
  - restricted filesystem access   (--read-only root fs, only /workspace writable)
  - only required input files      (only files in file_mapping are copied in)
  - temporary workspace            (fresh temp dir per run, removed after)

Captures: stdout, stderr, exit code, execution time.
"""

import os
import re
import shutil
import subprocess
import tempfile
import time
import uuid

IMAGE_NAME = "coding-agent-sandbox"
DEFAULT_TIMEOUT_SECONDS = 30
DEFAULT_MEMORY_LIMIT = "512m"
DEFAULT_CPU_LIMIT = "1.0"
CONTAINER_WORKDIR = "/workspace"


def _copy_input_files(file_mapping: dict, workspace: str) -> dict:
    """
    file_mapping: { "path referenced in generated code": "actual path on disk" }

    Copies each real file into the temp workspace (flat, by basename) and
    returns { "path referenced in generated code": "basename inside container" }
    so the caller can rewrite the code to point at the container path.
    """
    container_names = {}
    real_path_to_candidate = {}

    for code_path, real_path in file_mapping.items():
        if not real_path:
            continue
        if not os.path.isfile(real_path):
            raise FileNotFoundError(f"Input file not found on disk: {real_path}")

        # If this real path has already been copied, reuse the same container candidate name
        if real_path in real_path_to_candidate:
            container_names[code_path] = real_path_to_candidate[real_path]
            continue

        basename = os.path.basename(real_path)
        candidate = basename
        i = 1
        while candidate in real_path_to_candidate.values():
            name, ext = os.path.splitext(basename)
            candidate = f"{name}_{i}{ext}"
            i += 1

        shutil.copy2(real_path, os.path.join(workspace, candidate))
        real_path_to_candidate[real_path] = candidate
        container_names[code_path] = candidate

    return container_names


def _remap_paths_in_code(code: str, code_path_to_container_name: dict) -> str:
    """
    Replaces occurrences of original host/code path strings with their
    actual container path (/workspace/<filename>) without duplicate prefixing.
    """
    for code_path, container_name in code_path_to_container_name.items():
        container_path = f"{CONTAINER_WORKDIR}/{container_name}"
        variants = [
            code_path,
            code_path.replace("/", "\\"),
            code_path.replace("\\", "/"),
            f"/app/input/{container_name}",
            f"./{container_name}",
        ]
        # Replace longer variants first
        for variant in sorted(variants, key=len, reverse=True):
            if variant and variant != container_name and variant != container_path:
                code = code.replace(variant, container_path)

    # Normalize any accidental duplicate container workdir prefixes (e.g. /workspace//workspace/...)
    code = re.sub(rf"(?:{re.escape(CONTAINER_WORKDIR)}/)+", f"{CONTAINER_WORKDIR}/", code)
    return code


def run_in_sandbox(code: str, file_mapping: dict = None,
                    timeout_seconds: int = DEFAULT_TIMEOUT_SECONDS,
                    memory_limit: str = DEFAULT_MEMORY_LIMIT,
                    cpu_limit: str = DEFAULT_CPU_LIMIT,
                    image: str = IMAGE_NAME,
                    keep_workspace_on_failure: bool = True) -> dict:
    """
    Executes `code` inside an isolated Docker container.

    file_mapping: optional { "path the code refers to": "real path on disk" }.
                  Only these files are made available inside the sandbox.

    Returns:
      {
        "stdout": str,
        "stderr": str,
        "exit_code": int | None,
        "execution_time_seconds": float,
        "timed_out": bool,
        "workspace": str,
      }
    """
    file_mapping = file_mapping or {}
    workspace = tempfile.mkdtemp(prefix="sandbox_")
    container_name = f"sandbox_{uuid.uuid4().hex[:10]}"

    try:
        code_path_to_container_name = _copy_input_files(file_mapping, workspace)
        final_code = _remap_paths_in_code(code, code_path_to_container_name)

        script_path = os.path.join(workspace, "generated_code.py")
        with open(script_path, "w", encoding="utf-8") as f:
            f.write(final_code)

        docker_cmd = [
            "docker", "run",
            "--rm",
            "--name", container_name,
            "--network", "none",
            "--memory", memory_limit,
            "--cpus", str(cpu_limit),
            "--pids-limit", "128",
            "--cap-drop", "ALL",
            "--security-opt", "no-new-privileges",
            "--read-only",
            "--tmpfs", "/tmp:rw,size=64m",
            "-v", f"{workspace}:{CONTAINER_WORKDIR}:rw",
            "-w", CONTAINER_WORKDIR,
            image,
            "python", "generated_code.py",
        ]

        start = time.perf_counter()
        timed_out = False
        stdout, stderr, exit_code = "", "", None

        try:
            proc = subprocess.run(
                docker_cmd,
                capture_output=True,
                text=True,
                timeout=timeout_seconds,
            )
            stdout, stderr, exit_code = proc.stdout, proc.stderr, proc.returncode
        except subprocess.TimeoutExpired as e:
            timed_out = True
            stdout = e.stdout or ""
            stderr = (e.stderr or "") + "\n[sandbox] Execution timed out."
            exit_code = None
            subprocess.run(["docker", "kill", container_name],
                            capture_output=True, text=True)
        finally:
            elapsed = time.perf_counter() - start

        result = {
            "stdout": stdout,
            "stderr": stderr,
            "exit_code": exit_code,
            "execution_time_seconds": round(elapsed, 3),
            "timed_out": timed_out,
        }

        failed = timed_out or exit_code != 0
        if failed and keep_workspace_on_failure:
            result["workspace"] = workspace
        else:
            shutil.rmtree(workspace, ignore_errors=True)

        return result

    except Exception:
        shutil.rmtree(workspace, ignore_errors=True)
        raise


if __name__ == "__main__":
    sample_code = 'import json\nprint("___RESULT___" + json.dumps({"answer": "sandbox is working", "details": {}}))'
    result = run_in_sandbox(sample_code, file_mapping={}, timeout_seconds=15)
    print("=" * 60)
    for k, v in result.items():
        print(f"{k}: {v!r}")
