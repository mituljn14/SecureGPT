"""
Meeting Minutes Builder
-----------------------
Generates a professional DOCX meeting minutes document from the final
MeetingState using python-docx.

Output is saved to MINUTES_OUTPUT_DIR (default: backend/tmp_minutes/).
"""
import os
import logging
from datetime import datetime
from pathlib import Path

logger = logging.getLogger(__name__)

MINUTES_OUTPUT_DIR = Path(
    os.getenv("MINUTES_OUTPUT_DIR",
              str(Path(__file__).resolve().parents[2] / "tmp_minutes"))
)


# ---------------------------------------------------------------------------
# Styling helpers
# ---------------------------------------------------------------------------

def _add_heading(doc, text: str, level: int):
    """Add a heading with the given level."""
    doc.add_heading(text, level=level)


def _add_separator(doc):
    """Add a thin horizontal rule via a paragraph border."""
    from docx.oxml.ns import qn
    from docx.oxml import OxmlElement
    p = doc.add_paragraph()
    pPr = p._p.get_or_add_pPr()
    pBdr = OxmlElement("w:pBdr")
    bottom = OxmlElement("w:bottom")
    bottom.set(qn("w:val"), "single")
    bottom.set(qn("w:sz"), "6")
    bottom.set(qn("w:space"), "1")
    bottom.set(qn("w:color"), "4F81BD")
    pBdr.append(bottom)
    pPr.append(pBdr)


def _priority_color(priority: str) -> str:
    """Return a hex color string for each priority level."""
    return {
        "High": "C00000",
        "Medium": "E26B0A",
        "Low": "375623",
    }.get(priority, "000000")


# ---------------------------------------------------------------------------
# Main builder
# ---------------------------------------------------------------------------

def build_minutes_node(state: dict) -> dict:
    """
    LangGraph node: assemble and write the DOCX meeting minutes.

    Sets:
        state['minutes_path'] — absolute path to the written .docx file
        state['error']        — error string on failure
    """
    try:
        from docx import Document
        from docx.shared import Pt, RGBColor, Inches
        from docx.enum.text import WD_ALIGN_PARAGRAPH
        from docx.enum.table import WD_TABLE_ALIGNMENT
    except ImportError:
        state["error"] = "python-docx is not installed. Run: pip install python-docx"
        logger.error(state["error"])
        return state

    MINUTES_OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    job_id = state.get("job_id", "unknown")
    title = state.get("meeting_title", "Internal Meeting")
    summary = state.get("meeting_summary", "No summary available.")
    decisions = state.get("decisions", [])
    action_items = state.get("action_items", [])
    transcript = state.get("diarized_transcript") or state.get("raw_transcript", "")
    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M")

    doc = Document()

    # ── Page margins ────────────────────────────────────────────────────────
    for section in doc.sections:
        section.top_margin = Inches(1)
        section.bottom_margin = Inches(1)
        section.left_margin = Inches(1.2)
        section.right_margin = Inches(1.2)

    # ── Document title ──────────────────────────────────────────────────────
    title_para = doc.add_paragraph()
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = title_para.add_run("MEETING MINUTES")
    run.bold = True
    run.font.size = Pt(20)
    run.font.color.rgb = RGBColor(0x1F, 0x49, 0x7D)

    subtitle_para = doc.add_paragraph()
    subtitle_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub_run = subtitle_para.add_run(title)
    sub_run.font.size = Pt(14)
    sub_run.font.color.rgb = RGBColor(0x4F, 0x81, 0xBD)

    meta_para = doc.add_paragraph()
    meta_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    meta_run = meta_para.add_run(
        f"Generated by SecureGPT Meeting Agent  |  {generated_at}  "
        f"|  Job ID: {job_id}"
    )
    meta_run.font.size = Pt(9)
    meta_run.font.color.rgb = RGBColor(0x80, 0x80, 0x80)

    _add_separator(doc)
    doc.add_paragraph()

    # ── 1. Executive Summary ────────────────────────────────────────────────
    _add_heading(doc, "1. Executive Summary", level=1)
    doc.add_paragraph(summary)
    doc.add_paragraph()

    # ── 2. Decisions ────────────────────────────────────────────────────────
    _add_heading(doc, "2. Decisions", level=1)

    if decisions:
        table = doc.add_table(rows=1, cols=3)
        table.style = "Table Grid"
        table.alignment = WD_TABLE_ALIGNMENT.LEFT

        hdr_cells = table.rows[0].cells
        for i, heading_text in enumerate(["#", "Decision", "Rationale"]):
            p = hdr_cells[i].paragraphs[0]
            run = p.add_run(heading_text)
            run.bold = True
            run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            from docx.oxml.ns import qn
            from docx.oxml import OxmlElement
            tcPr = hdr_cells[i]._tc.get_or_add_tcPr()
            shd = OxmlElement("w:shd")
            shd.set(qn("w:val"), "clear")
            shd.set(qn("w:color"), "auto")
            shd.set(qn("w:fill"), "1F497D")
            tcPr.append(shd)

        for idx, dec in enumerate(decisions, start=1):
            row_cells = table.add_row().cells
            row_cells[0].text = str(idx)
            row_cells[1].text = dec.get("decision", "")
            row_cells[2].text = dec.get("rationale", "") or "—"

        for row in table.rows:
            row.cells[0].width = Inches(0.4)
            row.cells[1].width = Inches(3.5)
            row.cells[2].width = Inches(2.5)
    else:
        doc.add_paragraph("No formal decisions were recorded.")

    doc.add_paragraph()

    # ── 3. Action Items ─────────────────────────────────────────────────────
    _add_heading(doc, "3. Action Items", level=1)

    if action_items:
        table = doc.add_table(rows=1, cols=5)
        table.style = "Table Grid"
        table.alignment = WD_TABLE_ALIGNMENT.LEFT

        hdr_cells = table.rows[0].cells
        for i, heading_text in enumerate(["#", "Task", "Owner", "Deadline", "Priority"]):
            p = hdr_cells[i].paragraphs[0]
            run = p.add_run(heading_text)
            run.bold = True
            run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
            from docx.oxml.ns import qn
            from docx.oxml import OxmlElement
            tcPr = hdr_cells[i]._tc.get_or_add_tcPr()
            shd = OxmlElement("w:shd")
            shd.set(qn("w:val"), "clear")
            shd.set(qn("w:color"), "auto")
            shd.set(qn("w:fill"), "1F497D")
            tcPr.append(shd)

        for idx, item in enumerate(action_items, start=1):
            row_cells = table.add_row().cells
            row_cells[0].text = str(idx)
            row_cells[1].text = item.get("task", "")
            row_cells[2].text = item.get("owner", "Unknown")
            row_cells[3].text = item.get("deadline", "Not specified")
            priority = item.get("priority", "Medium")
            p = row_cells[4].paragraphs[0]
            run = p.add_run(priority)
            run.bold = True
            hex_col = _priority_color(priority)
            r, g, b = int(hex_col[0:2], 16), int(hex_col[2:4], 16), int(hex_col[4:6], 16)
            run.font.color.rgb = RGBColor(r, g, b)

        for row in table.rows:
            row.cells[0].width = Inches(0.35)
            row.cells[1].width = Inches(3.0)
            row.cells[2].width = Inches(1.2)
            row.cells[3].width = Inches(1.2)
            row.cells[4].width = Inches(0.8)
    else:
        doc.add_paragraph("No action items were identified.")

    doc.add_paragraph()

    # ── 4. Full Transcript ──────────────────────────────────────────────────
    _add_heading(doc, "4. Full Transcript", level=1)
    if transcript:
        t_para = doc.add_paragraph()
        t_run = t_para.add_run(transcript)
        t_run.font.size = Pt(9)
        t_run.font.color.rgb = RGBColor(0x40, 0x40, 0x40)
    else:
        doc.add_paragraph("Transcript not available.")

    # ── Footer note ─────────────────────────────────────────────────────────
    doc.add_paragraph()
    _add_separator(doc)
    footer_para = doc.add_paragraph()
    footer_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer_run = footer_para.add_run(
        "CONFIDENTIAL — Generated by SecureGPT Meeting Agent. "
        "Do not distribute outside authorised personnel."
    )
    footer_run.font.size = Pt(8)
    footer_run.font.color.rgb = RGBColor(0x80, 0x80, 0x80)
    footer_run.italic = True

    # ── Save ─────────────────────────────────────────────────────────────────
    out_path = MINUTES_OUTPUT_DIR / f"minutes_{job_id}.docx"
    doc.save(str(out_path))
    state["minutes_path"] = str(out_path)
    logger.info(f"[MinutesBuilder] DOCX saved: {out_path}")

    return state
